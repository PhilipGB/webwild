def vc(col,a=255):return list(col)+[a]
def xyz(p):return np.asarray(p,dtype=float)
def lerp(a,b,t):return xyz(a)*(1-t)+xyz(b)*t

def twist(y,a):return math.sin(y*2.7+a)*0.06

class Builder:
    def __init__(self):self.v=[];self.f=[];self.c=[]
    def tri(self,a,b,c,col,back=False):
        ix=len(self.v);self.v.extend([list(map(float,a)),list(map(float,b)),list(map(float,c))]);self.f.append([ix,ix+1,ix+2]);self.c.extend([vc(col)]*3)
        if back:self.tri(a,c,b,col)
    def quad(self,a,b,c,d,col,back=False):
        self.tri(a,b,c,col,back);self.tri(a,c,d,col,back)
    def mesh(self):
        m=trimesh.Trimesh(vertices=np.array(self.v),faces=np.array(self.f),process=False)
        m.visual.vertex_colors=np.array(self.c,dtype=np.uint8)
        return m

class Asset:
    def __init__(self,name):self.name=name;self.parts=OrderedDict()
    def part(self,n):return self.parts.setdefault(n,Builder())
    def mesh_count(self):return len(self.parts)
    def export(self,path):
        sc=trimesh.Scene(base_frame='world')
        for k,b in self.parts.items():
            if b.f:
                sc.add_geometry(b.mesh(),node_name=k,geom_name=k)
        path.parent.mkdir(parents=True,exist_ok=True)
        path.write_bytes(trimesh.exchange.gltf.export_glb(sc,include_normals=True))
        bounds=sc.bounds
        return {'name':self.name,'size_bytes':path.stat().st_size,'meshes':len(sc.geometry),
                'triangles':sum(len(g.faces) for g in sc.geometry.values()),
                'bounds_m':[[round(float(x),3) for x in row] for row in bounds],
                'size_m':[round(float(x),3) for x in bounds[1]-bounds[0]]}

def p3(x=0,y=0,z=0):return np.array([x,y,z],dtype=float)

def add_cylinder(b,a,c,r0,r1,n,col,cap=True):
    a=xyz(a);c=xyz(c);d=c-a;dn=np.linalg.norm(d)
    if dn<1e-5:return
    axis=d/dn;helper=p3(0,0,1) if abs(axis[2])<0.89 else p3(1,0,0)
    right=np.cross(axis,helper);right/=np.linalg.norm(right);forward=np.cross(axis,right)
    p=[a+(math.cos(i*2*PI/n)*right+math.sin(i*2*PI/n)*forward)*r0 for i in range(n)]
    q=[c+(math.cos(i*2*PI/n)*right+math.sin(i*2*PI/n)*forward)*r1 for i in range(n)]
    for i in range(n):
        j=(i+1)%n
        shade=tuple(max(0,min(255,x+([-14,0,12,5][i%4]))) for x in col)
        b.quad(p[i],p[j],q[j],q[i],shade)
        if cap:
            b.tri(a,p[j],p[i],col)
            b.tri(c,q[i],q[j],col)

def add_tube(b,points,radii,col,n=7):
    for i in range(len(points)-1):add_cylinder(b,points[i],points[i+1],radii[i],radii[i+1],n,col)

def add_sphere(b,center,scale,color,subdiv=1,variation=9):
    ico=trimesh.creation.icosphere(subdivisions=subdiv,radius=1.0)
    vv=ico.vertices*xyz(scale)+xyz(center)
    for fi,f in enumerate(ico.faces):
        delta=[-variation,0,variation,3][fi%4]
        shade=tuple(int(max(0,min(255,channel+delta))) for channel in color)
        b.tri(vv[f[0]],vv[f[1]],vv[f[2]],shade)

def add_leaf(b,origin,direction,length,width,base_y,tip_y,colors,sideways=0):
    origin=xyz(origin)
    d=xyz(direction);d[1]=0;d/=np.linalg.norm(d)
    side=np.cross(p3(0,1,0),d)
    path=[origin+p3(0,base_y,0),
      origin+d*length*.22+p3(0,base_y+(tip_y-base_y)*.24,0)+side*sideways*.18,
      origin+d*length*.62+p3(0,base_y+(tip_y-base_y)*.56,0)+side*sideways*.5,
      origin+d*length+p3(0,tip_y,0)+side*sideways]
    widths=[0.025,width*.32,width*.42,0.015]
    for i in range(3):
        a,b1=path[i],path[i+1]
        left=a-side*widths[i];right=a+side*widths[i]
        left1=b1-side*widths[i+1];right1=b1+side*widths[i+1]
        b.quad(left,left1,right1,right,colors[i%len(colors)],back=True)
        b.tri(left1,b1+ p3(0,0.012,0),right1,colors[(i+1)%len(colors)],back=True)

def add_pad(asset,name,center,rx,rz,y=0.08,theta=0,veins=True):
    b=asset.part(name+'_leaf');e=asset.part(name+'_edge');v=asset.part(name+'_veins')
    center=xyz(center); n=19; notch=.20; points=[];low=[]
    wobble=[1.03,1,1.015,.985,1.005,.98,1.03,.99,1.02,.97,1.02,.99,1.0,.97,1.025,1,.985,1.02,1.01,1.0]
    for i in range(n+1):
        angle=PI/2+notch+(2*PI-2*notch)*i/n+theta
        r=wobble[i%len(wobble)]
        pt=center+p3(math.cos(angle)*rx*r, y+0.017*math.cos(angle*3),math.sin(angle)*rz*r)
        points.append(pt);low.append(pt-p3(0,0.095,0))
    c=center+p3(0,y-0.009,-0.12*rz)
    for i in range(n):
        col=C[['pad_top','pad_light','pad_top','pad_dark'][i%4]]
        b.tri(c,points[i],points[i+1],col,back=True)
        e.quad(points[i],low[i],low[i+1],points[i+1],C['pad_edge'])
        e.tri(center-p3(0,.10,0),low[i+1],low[i],C['pad_under'])
        if veins and i%3==0:
            end=lerp(c,points[i],.83)+p3(0,.018,0)
            base=c+p3(0,.016,0)
            sid=p3(.012,0,0.012)
            v.tri(base-sid,base+sid,end,C['pad_vein'],back=True)
    for i in range(n-1):
        pass
    # Notched split edge naturally outlined by two short inner ribs.
    e.quad(c,points[0],low[0],c-p3(0,.095,0),C['pad_edge'],back=True)
    e.quad(c,points[-1],low[-1],c-p3(0,.095,0),C['pad_edge'],back=True)
    return c

def add_flower(asset,name,centre,scale=1.0,petal_color='petal_pink',n_petals=10,closed=False):
    p=xyz(centre);inner=asset.part(name+'_inner_petals');outer=asset.part(name+'_outer_petals');gold=asset.part(name+'_gold')
    if not closed:
        for ring in range(2):
            for i in range(n_petals):
                angle=2*PI*(i+(ring*.5))/n_petals
                d=p3(math.cos(angle),0,math.sin(angle));side=p3(-math.sin(angle),0,math.cos(angle))
                radius=.41*scale if ring==0 else .29*scale
                w=.20*scale if ring==0 else .14*scale
                h=.22*scale if ring==0 else .12*scale
                base=p+p3(0,.03*scale,0)
                mid=p+d*radius*.48+p3(0,h*.7,0)
                tip=p+d*radius+p3(0,h,0)
                col=C[petal_color] if ring==0 else C['petal_white']
                t=outer if ring==0 else inner
                t.tri(base,mid-side*w,mid+side*w,col,back=True)
                t.tri(mid-side*w,tip,mid+side*w,C['petal_light'] if ring==0 else col,back=True)
        add_sphere(gold,p+p3(0,.10*scale,0),(.10*scale,.065*scale,.10*scale),C['flower_gold'],subdiv=1)
        for i in range(8):
            th=i*2*PI/8
            add_sphere(gold,p+p3(.075*scale*math.cos(th),.16*scale,.075*scale*math.sin(th)),(.018*scale,.029*scale,.018*scale),C['flower_gold2'],subdiv=0,variation=0)
    else:
        add_tube(asset.part(name+'_stem'),[p-p3(0,.34*scale,0),p+p3(0,.035*scale,0)],[.035*scale,.026*scale],C['stem'],6)
        add_sphere(inner,p+p3(0,.08*scale,0),(.10*scale,.26*scale,.10*scale),C['petal_pink'],subdiv=1)
        for i in range(7):
            a=2*PI*i/7;d=p3(math.cos(a),0,math.sin(a));side=p3(-math.sin(a),0,math.cos(a))
            base=p+d*.11*scale;tip=p+d*.06*scale+p3(0,.36*scale,0)
            middle=p+d*.14*scale+p3(0,.16*scale,0)
            outer.tri(base,middle-side*.08*scale,tip,C['petal_pink'],back=True)
            outer.tri(base,tip,middle+side*.08*scale,C['petal_light'],back=True)
        for i in range(5):
            d=p3(math.cos(i*2*PI/5),0,math.sin(i*2*PI/5))
            leaf=asset.part(name+'_sepal')
            leaf.tri(p-p3(0,.09*scale,0),p+d*.16*scale, p+d*.085*scale+p3(0,.19*scale,0),C['stem_light'],back=True)

def add_cattail(asset,name,base,scale=1.0,bend=0):
    base=xyz(base);stem=asset.part(name+'_stalk');head=asset.part(name+'_seed_head');highlight=asset.part(name+'_seed_texture');leaves=asset.part(name+'_leaves')
    h=1.55*scale;tip=base+p3(.10*bend,h,0.06*bend)
    bend1=base+p3(.06*bend,h*.55,0.04*bend)
    add_tube(stem,[base,bend1,tip],[.045*scale,.034*scale,.022*scale],C['stem'],n=7)
    core=base+p3(.09*bend,h*.79,.06*bend)
    # Seed pod elongated, blunt ends, faceted not ellipsoidal cylinder.
    end=base+p3(.1*bend,h*.955,.06*bend)
    add_cylinder(head,core,end,.12*scale,.105*scale,10,C['cattail'])
    add_sphere(head,core,(.12*scale,.13*scale,.12*scale),C['cattail'],subdiv=1)
    add_sphere(head,end,(.10*scale,.11*scale,.10*scale),C['cattail_light'],subdiv=1)
    for i in range(6):
        a=2*PI*i/6
        p=core+p3(math.cos(a)*.116*scale,.08*scale,math.sin(a)*.116*scale)
        add_sphere(highlight,p,(.013*scale,.025*scale,.013*scale),C['cattail_light'],subdiv=0,variation=0)
    for i in range(3):
        angle=2*PI*(i+.15)/3
        d=p3(math.cos(angle),0,math.sin(angle))
        add_leaf(leaves,base,d,.47*scale,.10*scale,0,.65*scale, [C['stem_light'],C['stem'],C['grass_pale']],sideways=.05*scale)

def add_grass(asset,name,pos,scale=1,blades=10):
    base=xyz(pos)
    b=asset.part(name+'_blades')
    for i in range(blades):
        a=2*PI*i/blades+.22*math.sin(i*9)
        d=p3(math.cos(a),0,math.sin(a))
        length=scale*(.30+(i%5)*.09)
        top=.26*scale+((i*3)%6)*.09*scale
        add_leaf(b,base+d*.035,d,length,.045*scale+(i%4)*.006,0,top,[C['grass'],C['stem_light'],C['grass_pale']],sideways=.12*math.sin(i*3))

def add_island(asset,name,radx,radz,seed):
    rng=random.Random(seed);soil=asset.part('Faceted_earth_bank');grass=asset.part('Grass_turf');moss=asset.part('Moss_streaks');stones=asset.part('Waterline_stones')
    n=24;yTop=.12;radii=[0.6,.92,1,.93,.78]
    yy=[-0.73,-0.49,-0.14,.10,.13]
    phase=rng.uniform(-.1,.1)
    wobble=[1+rng.uniform(-.13,.13) for _ in range(n)]
    rings=[]
    for j,(fac,y) in enumerate(zip(radii,yy)):
        ring=[]
        for i in range(n):
            a=2*PI*i/n+phase
            r=fac*wobble[i]
            ring.append(p3(math.cos(a)*radx*r,y+(.025*math.sin(3*a) if j==4 else 0),math.sin(a)*radz*r))
        rings.append(ring)
    for j in range(len(rings)-1):
        for i in range(n):
            k=(i+1)%n
            palette=[C['earth_dark'],C['earth'],C['earth_light'],C['grass']][j]
            col=tuple(max(0,min(255,c+[-10,0,9,4][i%4])) for c in palette)
            (grass if j==3 else soil).quad(rings[j][i],rings[j][k],rings[j+1][k],rings[j+1][i],col)
    center=p3(0,.145,0)
    for i in range(n):
        j=(i+1)%n
        col=C[['grass','moss','grass_pale','grass'][i%4]]
        grass.tri(center,rings[-1][i],rings[-1][j],col)
    for i in range(10):
        angle=rng.uniform(0,2*PI);rr=rng.uniform(.25,.75)
        x=radx*rr*math.cos(angle);z=radz*rr*math.sin(angle)
        cr=rng.uniform(.10,.24)*min(radx,radz)
        cen=p3(x,.145,z)
        segments=5
        pts=[cen+p3(cr*math.cos(2*PI*k/segments),.01,cr*.75*math.sin(2*PI*k/segments)) for k in range(segments)]
        for k in range(segments):moss.tri(cen,pts[k],pts[(k+1)%segments],C['moss_light'] if i%2 else C['moss'])
    for i in range(max(3,round((radx+radz)*2))):
        a=2*PI*i/max(3,round((radx+radz)*2))
        pt=p3(radx*.80*math.cos(a),-.43,radz*.80*math.sin(a))
        add_sphere(stones,pt,(.13,.08,.10),C['rock_light'] if i%2 else C['rock'],subdiv=0,variation=6)
    for i in range(max(3,round(radx+radz))):
        a=rng.uniform(0,2*PI);r=rng.uniform(.25,.72)
        pos=p3(radx*r*math.cos(a),.17,radz*r*math.sin(a))
        add_grass(asset,f'Clump_{i}',pos,scale=.30+rng.uniform(-.03,.1),blades=4)

