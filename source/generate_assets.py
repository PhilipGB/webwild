def add_dragonfly(asset):
    body=asset.part('Body_segments');head=asset.part('Face_and_eyes');veins=asset.part('Wing_veins');wings=asset.part('Four_faceted_wings');legs=asset.part('Six_legs')
    # Origin is at bottom of flying silhouette; +Z points backwards.
    add_sphere(body,p3(0,.35,-.08),(.16,.13,.27),C['dragon'],subdiv=1)
    add_sphere(head,p3(0,.37,-.36),(.17,.145,.16),C['azure'],subdiv=2,variation=5)
    for sign in [-1,1]:
        eye=p3(sign*.105,.43,-.47)
        add_sphere(head,eye,(.074,.080,.062),C['eyes'],subdiv=1,variation=0)
        add_sphere(head,eye+p3(sign*.018,.038,-.04),(.021,.024,.013),C['eye_glint'],subdiv=0,variation=0)
    for i in range(7):
        z=.09+i*.105
        rad=.108-i*.010
        add_sphere(body,p3(0,.34+twist(i*.2,.4),z),(rad,rad*.82,.10),C['azure_dark'] if i%2 else C['dragon'],subdiv=1,variation=3)
    # Wing planes at y=.44: two wings per side, front swept and back swept.
    for side in [-1,1]:
        for wingno in [0,1]:
            z0=-.14 if wingno==0 else .03
            root=p3(side*.10,.45,z0)
            mid=p3(side*.51,.53,z0+(-.16 if wingno==0 else .16))
            tip=p3(side*.91,.54,z0+(-.22 if wingno==0 else .26))
            lead=p3(side*.48,.53,z0+(-.31 if wingno==0 else .02))
            trail=p3(side*.48,.53,z0+(.10 if wingno==0 else .36))
            wings.tri(root,lead,tip,C['wing'],back=True)
            wings.tri(root,tip,trail,C['wing_bright'],back=True)
            wings.tri(root,trail,lead,C['azure_light'],back=True)
            for dest in [mid,tip,lead,trail]:
                add_tube(veins,[root,dest],[.008,.003],C['wing_vein'],n=4)
        for i in range(3):
            k=-.25+i*.13
            add_tube(legs,[p3(side*.11,.28,k),p3(side*.22,.17,k+.05),p3(side*.30,.10,k+.07)],[.016,.012,.006],C['dragon_dark'],5)


